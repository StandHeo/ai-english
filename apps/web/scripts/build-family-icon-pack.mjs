const raw = JSON.parse(readFileSync(mdiPath, 'utf8'))
const allIcons = raw.icons || {}
const allNames = new Set(Object.keys(allIcons))

const wanted = new Set()
for (const n of SEED_NAMES) {
  if (allNames.has(n)) wanted.add(n)
}
for (const target of Object.values(ALIASES)) {
  if (allNames.has(target)) wanted.add(target)
}

// 再捞一批「单词级」图标名（无连字符或短横线少），提高冷门词命中
for (const name of allNames) {
  if (wanted.size >= 450) break
  if (!/^[a-z]+(-[a-z0-9]+){0,2}$/.test(name)) continue
  if (name.length < 3 || name.length > 18) continue
  const skip =
    /^(ab-|account-|alpha-|numeric-|roman-|clipboard-|file-|folder-|database-|server-|cloud-|code-|git-|npm-|css-|xml-)/.test(
      name,
    )
  if (skip) continue
  wanted.add(name)
}

const icons = {}
for (const name of wanted) {
  icons[name] = allIcons[name]
}

const pack = {
  prefix: 'mdi',
  width: raw.width || 24,
  height: raw.height || 24,
  aliases: ALIASES,
  icons,
}

const outDir = join(root, 'src', 'icons')
mkdirSync(outDir, { recursive: true })
const outPath = join(outDir, 'familyIconPack.json')
writeFileSync(outPath, JSON.stringify(pack))
const kb = (Buffer.byteLength(JSON.stringify(pack)) / 1024).toFixed(1)
console.log(`Wrote ${outPath}`)
console.log(`icons=${Object.keys(icons).length} size≈${kb}KB aliases=${Object.keys(ALIASES).length}`)
